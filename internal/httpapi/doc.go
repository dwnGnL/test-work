// Package httpapi — HTTP-слой для партнёров (счета, статус, баланс) и ручки управления симулятором сети.
// Бизнес-логики здесь нет: пакет разбирает запросы, вызывает функции модулей partners,
// invoices и ledger и превращает их ошибки в ответы.
//
// Маршруты: POST /v1/invoices, GET /v1/invoices/{id}, GET /v1/balance (нужен вход) и GET /healthz.
// Вход — заголовок Authorization: Bearer <API-ключ>; партнёр попадает в контекст запроса,
// и все обращения к данным идут только с его id. Ответ по счёту содержит платежи: amount_received
// и status считаются по payments.Summary (сумма зачисленных платежей до комиссии), массив
// payments — по payments.ListByInvoice.
//
// Ручки управления симулятором сети (POST /sim/transfers, /sim/blocks, /sim/reorg) работают
// без входа и только при включённом флаге SIM_API; иначе маршрутов нет и ответ — 404. Суммы в JSON только строками вида
// "100.000000". Ошибки всегда в формате {"error":{"code":"...","message":"..."}}:
// подробности внутренних ошибок попадают в лог, а не в ответ.
//
// Схемы Postgres нет: модуль без собственного состояния.
//
// Границы модуля: в базу напрямую не ходит (SQL здесь нет, пул только передаётся в функции
// других пакетов), с остальными модулями общается только через интерфейсы их пакетов.
// Так модуль можно вынести в отдельный сервис, поменяв транспорт, а не логику.

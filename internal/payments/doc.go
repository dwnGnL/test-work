// Package payments — обработчик платежей: порог подтверждений, AML-проверка, затем зачисление или возврат.
// Один перевод — одна запись, ключ (tx_hash, log_index).
//
// Схема Postgres: payments (таблица payments.payments; она же очередь обработки).
// Вердикт AML (aml_verdict: low или high) и время проверки (aml_checked_at) хранит платёж:
// модуль aml состояния не ведёт. CHECK-ограничения базы пускают платёж в credited только
// с вердиктом low, а в rejected — только с вердиктом high, так что деньги не попадают
// на баланс партнёра до ответа AML.
//
// Границы модуля: SQL модуля обращается только к его схеме; ссылки на сущности
// других модулей хранятся как id без внешних ключей; вызовы между модулями
// идемпотентны по ключу. Так модуль можно вынести в отдельный сервис, поменяв
// транспорт, а не логику.

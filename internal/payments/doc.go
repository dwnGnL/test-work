// Package payments — платежи: приём входящих переводов (обнаружение, откат при реорге, порог
// подтверждений), затем AML-проверка и зачисление или возврат. Один перевод — одна запись,
// ключ (tx_hash, log_index); блок — изменяемый атрибут платежа, а не часть ключа.
//
// Схема Postgres: payments (таблица payments.payments; она же очередь обработки).
// Вердикт AML (aml_verdict: low или high) и время проверки (aml_checked_at) хранит платёж:
// модуль aml состояния не ведёт. CHECK-ограничения базы пускают платёж в credited только
// с вердиктом low, а в rejected — только с вердиктом high, так что деньги не попадают
// на баланс партнёра до ответа AML.
//
// Статусы (тип Status): detected, orphaned, aml_pending, credited, rejected. Сейчас реализованы
// переходы до aml_pending; решение AML — следующий этап.
//
//   - Detect — перевод замечен в блоке: создаёт платёж detected, возвращает orphaned в detected
//     (транзакция включена заново) и обновляет блок у detected; остальное не трогает;
//   - OrphanFrom — реорг: платежи detected из выброшенных блоков становятся orphaned. Платежи,
//     прошедшие порог, не меняются, а только считаются (реорг глубже порога не обрабатывается);
//   - ConfirmReady — платёж набрал N подтверждений: в одной транзакции detected → aml_pending
//     и проводка шага 1 (hold, ключ {payment_id}:1). До порога проводок нет;
//   - Summary и ListByInvoice — чтение для API: сумма зачисленного до комиссии, признак
//     «есть платежи в обработке» и список платежей счёта.
//
// Параллельная и повторная обработка безопасна без мьютексов: корректность держат база и ledger —
// уникальный ключ платежа, условная смена статуса (WHERE status = 'detected') и ключ проводки.
//
// Границы модуля: SQL модуля обращается только к его схеме; ссылки на сущности
// других модулей хранятся как id без внешних ключей; вызовы между модулями
// идемпотентны по ключу. Так модуль можно вынести в отдельный сервис, поменяв
// транспорт, а не логику.

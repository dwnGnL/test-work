// Package chain — доступ к блокчейну за интерфейсом Chain. Реализация в этом проекте — симулятор сети
// (Simulator): создаёт входящие переводы USDT, добавляет блоки и подтверждения, откатывает блоки (реорг).
// Реальная реализация через RPC не нужна.
//
// Интерфейс Chain — ровно то, что нужно сканеру: номер последнего блока, заголовок блока по номеру
// и события Transfer блока по его хэшу (как eth_getLogs по blockHash). Хэши, адреса и переводы
// всегда в нижнем регистре.
//
// Схема Postgres: chainsim (blocks, transfers) — это состояние «внешней» сети, а не сервиса,
// поэтому «сеть» переживает рестарт; остальные модули читают её только через интерфейс пакета.
//
// Симулятор, кроме Chain, умеет управляться:
//   - SubmitTx — одна транзакция с одним или несколькими событиями Transfer (log_index 0..n-1)
//     попадает в мемпул (переводы без блока);
//   - Mine — добывает блоки; первый забирает весь мемпул, остальные пустые (подтверждения);
//   - Reorg — выбрасывает последние блоки: их транзакции либо возвращаются в мемпул и попадут
//     в следующий блок с другим хэшем, либо исчезают совсем.
//
// Нулевого блока нет: нумерация идёт с единицы, пока блоков нет, Head возвращает 0, а у первого
// блока parent_hash состоит из нулей. Хэши блоков и транзакций случайные (crypto/rand).
// Mine и Reorg выстраиваются в очередь блокировкой базы, поэтому параллельные вызовы
// не создают в цепочке дыр и повторов.
//
// Границы модуля: SQL модуля обращается только к его схеме; ссылки на сущности
// других модулей хранятся как id без внешних ключей; вызовы между модулями
// идемпотентны по ключу. Так модуль можно вынести в отдельный сервис, поменяв
// транспорт, а не логику.

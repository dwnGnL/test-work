// Package scanner — сканер блоков: читает блоки через chain.Chain, находит переводы USDT на депозитные
// адреса счетов, ведёт курсор и обнаруживает реорги по хэшам блоков.
//
// Схема Postgres: scanner (таблица scanner.blocks — обработанные блоки: номер, хэш, parent_hash).
// Последний блок в ней — курсор: после рестарта сканер продолжает с него, блоки за время простоя
// не теряются. Таблица не чистится (упрощение; в проде — удалять блоки глубже финализации).
//
// Один проход — Tick, его вызывает фоновая горутина по таймеру, а тесты напрямую:
//  1. из пула берётся одно соединение и на нём блокировка «сканер один» (pg_try_advisory_lock):
//     второй экземпляр пропускает проход. Вся работа прохода с базой идёт через это же соединение,
//     поэтому оборвавшееся соединение останавливает проход, а не оставляет «зомби», который пишет
//     без блокировки. После ошибки или паники соединение закрывается, а не возвращается в пул;
//  2. сверка последнего своего блока с сетью; при расхождении — откат до общего предка, платежи
//     выброшенных блоков становятся orphaned (payments.OrphanFrom);
//  3. чтение новых блоков по одному; запись о блоке и платежи (payments.Detect) — одна транзакция;
//  4. перед подтверждением курсор (последний обработанный блок) проверяется по сети; платежи,
//     набравшие N подтверждений от курсора, а не от головы сети, переходят в aml_pending
//     (payments.ConfirmReady). Курсор пропал из сети — возврат к шагу 2;
//  5. блокировка снимается (pg_advisory_unlock) на том же соединении, оно возвращается в пул.
//
// Принимаются только события контракта USDT из конфигурации (поддельный токен с тем же именем
// игнорируется) и только с суммой больше нуля. Событий неуспешных транзакций в логах нет, поэтому
// отдельной проверки статуса транзакции не нужно. Реорг глубже порога подтверждений не
// обрабатывается: платежи за порогом не трогаются, в лог пишется ошибка.
//
// Границы модуля: SQL модуля обращается только к его схеме; ссылки на сущности
// других модулей хранятся как id без внешних ключей; вызовы между модулями
// идемпотентны по ключу. Так модуль можно вынести в отдельный сервис, поменяв
// транспорт, а не логику.

// Package refunds — возвраты отправителям: отдельная сущность со статусом, один платёж — один возврат.
// Отправка в сеть не реализуется, возврат доводится до ready_to_send.
//
// Схема Postgres: refunds (таблица refunds.refunds). payment_id уникален: «один платёж — один
// возврат» держит база, а не код.
//
// Статусы (тип Status): created, ready_to_send.
//
//   - Create — возврат создаётся в транзакции вызывающего, вместе с отказом по платежу.
//     Повтор по тому же платежу возвращает уже созданный возврат и не создаёт второй;
//   - MarkReady — условный перевод created → ready_to_send; повтор ничего не меняет;
//   - ByPayments — чтение для API: возвраты перечисленных платежей.
//
// Границы модуля: SQL модуля обращается только к его схеме; ссылки на сущности
// других модулей хранятся как id без внешних ключей; вызовы между модулями
// идемпотентны по ключу. Так модуль можно вынести в отдельный сервис, поменяв
// транспорт, а не логику.

-- Модуль invoices: адрес депозита хранится только в нижнем регистре.
-- Адрес в смешанном регистре (EIP-55) сканер не найдёт: из лога он приходит в нижнем,
-- и платёж молча остался бы без счёта; кроме того, UNIQUE пропустил бы два счёта
-- с одним и тем же адресом в разном регистре. Приведение к нижнему регистру — на
-- входе в код, а база не даёт сохранить иное.
ALTER TABLE invoices.invoices
  ADD CONSTRAINT invoices_deposit_address_lowercase CHECK (deposit_address = lower(deposit_address));
